const char* languageName(Language language) {
    switch (language) {
        case Language::English: return "en";
        case Language::PortugueseBrazil: return "pt-BR";
    }
    return "en";
}

const char* languageLabel(Language language) {
    switch (language) {
        case Language::English: return "ENGLISH";
        case Language::PortugueseBrazil: return "PORTUGUES (BR)";
    }
    return "ENGLISH";
}

std::optional<Language> languageFromName(const std::string& name) {
    if (name == "en" || name == "EN" || name == "ENGLISH") {
        return Language::English;
    }
    if (name == "pt-BR" || name == "pt_BR" || name == "PT-BR" ||
        name == "PT_BR" || name == "PORTUGUES (BR)") {
        return Language::PortugueseBrazil;
    }
    return std::nullopt;
}

Language nextLanguage(Language language, int direction) {
    if (direction == 0) {
        return language;
    }
    return language == Language::English ? Language::PortugueseBrazil : Language::English;
}

const char* uiText(UiText text, Language language) {
    const LocalizedText& row = rowFor(text);
    return language == Language::PortugueseBrazil ? row.ptBR : row.en;
}

