const char* CpCapsuleCutscene::sourceObjAtlasPath(int atlasPage) {
    if (atlasPage < 0 ||
        atlasPage >= static_cast<int>(sizeof(kSourceObjAtlasPages) / sizeof(kSourceObjAtlasPages[0]))) {
        return "";
    }
    return kSourceObjAtlasPages[atlasPage];
}

